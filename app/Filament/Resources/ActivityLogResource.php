<?php

namespace App\Filament\Resources;

use App\Filament\Resources\ActivityLogResource\Pages;
use App\Models\User;
use App\Support\AuditLog;
use Filament\Forms;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Spatie\Activitylog\Models\Activity;

/**
 * Read-only journal of user actions (spatie/laravel-activitylog), for administrators.
 * Field names and values are shown as stored: the journal is a technical tool.
 */
class ActivityLogResource extends Resource
{
    protected static ?string $model = Activity::class;

    protected static ?string $navigationIcon = 'heroicon-o-clipboard-document-list';

    protected static ?int $navigationSort = 9;

    protected static ?string $slug = 'activity-log';

    public static function getNavigationLabel(): string
    {
        return __('Activity log');
    }

    public static function getModelLabel(): string
    {
        return __('Activity log entry');
    }

    public static function getPluralModelLabel(): string
    {
        return __('Activity log');
    }

    public static function getNavigationGroup(): ?string
    {
        return __('Settings');
    }

    /**
     * @return array<string, string>
     */
    public static function logNameLabels(): array
    {
        return [
            AuditLog::LOG_RECORDS => __('Records and settings'),
            AuditLog::LOG_SCHEDULE => __('Schedule'),
            AuditLog::LOG_AUTH => __('Sign-in'),
        ];
    }

    /**
     * @return array<string, string>
     */
    public static function eventLabels(): array
    {
        return [
            'created' => __('Created'),
            'updated' => __('Updated'),
            'deleted' => __('Deleted'),
            'relations_updated' => __('Relations updated'),
            'autogenerated' => __('Auto-generation'),
            'draft_created' => __('Draft created'),
            'draft_duplicated' => __('Draft duplicated'),
            'draft_renamed' => __('Draft renamed'),
            'draft_deleted' => __('Draft deleted'),
            'draft_cleared' => __('Draft cleared'),
            'draft_approved' => __('Draft approved'),
            'month_cleared' => __('Month cleared'),
            'login' => __('Signed in'),
            'logout' => __('Signed out'),
            'login_failed' => __('Failed sign-in'),
        ];
    }

    /**
     * The journal filtered to one record, for the "History" actions.
     */
    public static function historyUrl(Model $record): string
    {
        return static::historyUrlFor($record->getMorphClass(), $record->getKey());
    }

    public static function historyUrlFor(string $subjectType, int|string $subjectId): string
    {
        return static::getUrl('index', ['tableFilters' => ['subject' => ['type' => $subjectType, 'id' => $subjectId]]]);
    }

    public static function subjectLabel(Activity $activity): ?string
    {
        if ($activity->subject_type === null) {
            return null;
        }

        $name = $activity->subject?->name ?? $activity->properties->get('name');

        return class_basename($activity->subject_type).' #'.$activity->subject_id.($name ? ' · '.$name : '');
    }

    /**
     * Short overview of the stored properties: changed attributes or the operation figures.
     */
    public static function summary(Activity $activity): string
    {
        $properties = $activity->properties;

        if ($properties->has('attributes')) {
            return implode(', ', array_keys($properties->get('attributes')));
        }

        if ($properties->has('relations')) {
            return implode(', ', array_keys($properties->get('relations')));
        }

        return collect($properties->all())
            ->reject(fn ($value): bool => is_array($value))
            ->map(fn ($value, string $key): string => $key.': '.static::formatValue($value))
            ->implode(', ');
    }

    public static function formatValue(mixed $value): string
    {
        return match (true) {
            $value === null => '—',
            is_bool($value) => $value ? 'true' : 'false',
            is_array($value) => json_encode($value, JSON_UNESCAPED_UNICODE),
            default => (string) $value,
        };
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                Tables\Columns\TextColumn::make('created_at')
                    ->label(__('Time'))
                    ->dateTime('d.m.Y H:i:s')
                    ->sortable(),
                Tables\Columns\TextColumn::make('causer.name')
                    ->label(__('User'))
                    ->placeholder(__('System')),
                Tables\Columns\TextColumn::make('log_name')
                    ->label(__('Area'))
                    ->badge()
                    ->color(fn (?string $state): string => match ($state) {
                        AuditLog::LOG_SCHEDULE => 'primary',
                        AuditLog::LOG_AUTH => 'warning',
                        default => 'gray',
                    })
                    ->formatStateUsing(fn (?string $state): string => static::logNameLabels()[$state] ?? (string) $state),
                Tables\Columns\TextColumn::make('event')
                    ->label(__('Action'))
                    ->formatStateUsing(fn (?string $state): string => static::eventLabels()[$state] ?? (string) $state),
                Tables\Columns\TextColumn::make('subject_type')
                    ->label(__('Object'))
                    ->state(fn (Activity $record): ?string => static::subjectLabel($record))
                    ->placeholder('—'),
                Tables\Columns\TextColumn::make('properties')
                    ->label(__('Details'))
                    ->state(fn (Activity $record): string => static::summary($record))
                    ->limit(80)
                    ->wrap(),
            ])
            ->defaultSort('created_at', 'desc')
            ->filters([
                Tables\Filters\SelectFilter::make('causer')
                    ->label(__('User'))
                    ->options(fn (): array => User::query()->orderBy('name')->pluck('name', 'id')->all())
                    ->searchable()
                    ->query(fn (Builder $query, array $data): Builder => filled($data['value'])
                        ? $query->where('causer_type', (new User)->getMorphClass())->where('causer_id', $data['value'])
                        : $query),
                Tables\Filters\SelectFilter::make('log_name')
                    ->label(__('Area'))
                    ->options(static::logNameLabels()),
                Tables\Filters\SelectFilter::make('event')
                    ->label(__('Action'))
                    ->options(static::eventLabels()),
                Tables\Filters\Filter::make('subject')
                    ->form([
                        Forms\Components\Select::make('type')
                            ->label(__('Object type'))
                            ->options(fn (): array => Activity::query()->whereNotNull('subject_type')->distinct()
                                ->orderBy('subject_type')->pluck('subject_type')
                                ->mapWithKeys(fn (string $type): array => [$type => class_basename($type)])->all()),
                        Forms\Components\TextInput::make('id')
                            ->label(__('Object ID'))
                            ->integer(),
                    ])
                    ->query(fn (Builder $query, array $data): Builder => $query
                        ->when($data['type'] ?? null, fn (Builder $q, string $type) => $q->where('subject_type', $type))
                        ->when($data['id'] ?? null, fn (Builder $q, $id) => $q->where('subject_id', $id)))
                    ->indicateUsing(fn (array $data): ?string => filled($data['type'] ?? null) || filled($data['id'] ?? null)
                        ? __('Object').': '.class_basename((string) ($data['type'] ?? '')).(filled($data['id'] ?? null) ? ' #'.$data['id'] : '')
                        : null),
                Tables\Filters\Filter::make('created_at')
                    ->form([
                        Forms\Components\DatePicker::make('from')->label(__('From date')),
                        Forms\Components\DatePicker::make('until')->label(__('To date')),
                    ])
                    ->query(fn (Builder $query, array $data): Builder => $query
                        ->when($data['from'] ?? null, fn (Builder $q, string $date) => $q->whereDate('created_at', '>=', $date))
                        ->when($data['until'] ?? null, fn (Builder $q, string $date) => $q->whereDate('created_at', '<=', $date)))
                    ->indicateUsing(fn (array $data): ?string => filled($data['from'] ?? null) || filled($data['until'] ?? null)
                        ? __('Date').': '.($data['from'] ?? '…').' – '.($data['until'] ?? '…')
                        : null),
            ])
            ->filtersFormColumns(2)
            ->actions([
                Tables\Actions\ViewAction::make()
                    ->modalHeading(fn (Activity $record): string => static::eventLabels()[$record->event] ?? (string) $record->event)
                    ->modalContent(fn (Activity $record) => view('filament.activity-log.details', ['activity' => $record]))
                    ->form([]),
            ])
            ->modifyQueryUsing(fn (Builder $query) => $query->with(['causer', 'subject']));
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListActivities::route('/'),
        ];
    }
}
