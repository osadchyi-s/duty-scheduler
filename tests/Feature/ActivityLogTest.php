<?php

use App\Filament\Resources\ActivityLogResource;
use App\Filament\Resources\ActivityLogResource\Pages\ListActivities;
use App\Filament\Resources\UserResource\Pages\EditUser;
use App\Jobs\PruneActivityLog;
use App\Models\EmployeeGroup;
use App\Models\EventType;
use App\Models\User;
use App\Models\UserEvent;
use App\Services\AutoScheduler;
use App\Services\ScheduleDraftService;
use Carbon\Carbon;
use Filament\Facades\Filament;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Queue;
use Livewire\Livewire;
use Spatie\Activitylog\Models\Activity;
use Spatie\Permission\Models\Role;

beforeEach(function () {
    config(['scheduling.time_unit' => 'days']);
    foreach (['Admin', 'Manager', 'User'] as $role) {
        Role::firstOrCreate(['name' => $role, 'guard_name' => 'web']);
    }
    $this->admin = User::create(['name' => 'Адмін', 'email' => 'admin@test.local', 'password' => 'secret-password']);
    $this->admin->assignRole('Admin');

    $this->duty = EventType::create([
        'name' => 'Чергування', 'code' => 'duty', 'color_code' => '#3B82F6', 'min_capacity' => 1, 'max_capacity' => 1,
        'default_duration_hours' => 24, 'is_schedulable' => true, 'is_work_time' => true, 'is_active' => true,
    ]);
    $this->employee = User::create(['name' => 'Працівник', 'email' => 'employee@test.local', 'password' => 'secret-password']);
    $this->employee->assignRole('User');
    $this->employee->allowedEventTypes()->attach($this->duty->id);

    Filament::setCurrentPanel(Filament::getPanel('admin'));
    $this->actingAs($this->admin);
    Activity::query()->delete();
});

function lastActivity(): Activity
{
    return Activity::query()->latest('id')->firstOrFail();
}

it('logs changed profile attributes but never the password', function () {
    $this->employee->update(['position' => 'Черговий', 'password' => 'another-password']);

    $activity = lastActivity();

    expect($activity->event)->toBe('updated')
        ->and($activity->log_name)->toBe('records')
        ->and($activity->causer_id)->toBe($this->admin->id)
        ->and($activity->properties->get('attributes'))->toBe(['position' => 'Черговий'])
        ->and(json_encode($activity->properties))->not->toContain('password');
});

it('logs events of the approved schedule but not events of drafts', function () {
    UserEvent::create(['user_id' => $this->employee->id, 'event_type_id' => $this->duty->id,
        'starts_at' => '2026-11-02 00:00:00', 'ends_at' => '2026-11-03 00:00:00']);
    expect(Activity::query()->where('log_name', 'schedule')->where('event', 'created')->count())->toBe(1);

    $draft = app(ScheduleDraftService::class)->create(Carbon::parse('2026-11-01'), $this->admin);
    UserEvent::create(['schedule_draft_id' => $draft->id, 'user_id' => $this->employee->id, 'event_type_id' => $this->duty->id,
        'starts_at' => '2026-11-05 00:00:00', 'ends_at' => '2026-11-06 00:00:00']);

    expect(Activity::query()->where('event', 'created')->count())->toBe(1)
        ->and(lastActivity()->event)->toBe('draft_created')
        ->and(lastActivity()->properties->get('copied_events'))->toBe(1);
});

it('logs one summary entry per auto-generation', function () {
    $draft = app(ScheduleDraftService::class)->create(Carbon::parse('2026-11-01'), $this->admin);

    app(AutoScheduler::class)->generate(Carbon::parse('2026-11-01'), Carbon::parse('2026-11-05')->endOfDay(), [$this->duty->id], draft: $draft);

    $activity = lastActivity();
    expect(Activity::query()->count())->toBe(2) // draft_created + autogenerated
        ->and($activity->event)->toBe('autogenerated')
        ->and($activity->subject_id)->toBe($draft->id)
        ->and($activity->properties->get('created'))->toBe(5);
});

it('logs one summary entry per draft approval', function () {
    $service = app(ScheduleDraftService::class);
    $draft = $service->create(Carbon::parse('2026-11-01'), $this->admin);
    foreach (['2026-11-02', '2026-11-04'] as $day) {
        UserEvent::create(['schedule_draft_id' => $draft->id, 'user_id' => $this->employee->id, 'event_type_id' => $this->duty->id,
            'starts_at' => "$day 00:00:00", 'ends_at' => Carbon::parse($day)->addDay()]);
    }

    $service->approve($draft, [], $this->admin);

    expect(Activity::query()->where('event', 'created')->count())->toBe(0)
        ->and(lastActivity()->event)->toBe('draft_approved')
        ->and(lastActivity()->properties->only(['added', 'removed', 'kept'])->all())->toBe(['added' => 2, 'removed' => 0, 'kept' => 0]);
});

it('logs relation changes made on the user edit page', function () {
    $night = EmployeeGroup::create(['name' => 'Нічні']);
    $this->employee->employeeGroups()->attach(EmployeeGroup::create(['name' => 'Денні'])->id);

    Livewire::test(EditUser::class, ['record' => $this->employee->getRouteKey()])
        ->fillForm(['employeeGroups' => [$night->id]])
        ->call('save')
        ->assertHasNoFormErrors();

    $activity = Activity::query()->where('event', 'relations_updated')->sole();
    expect($activity->subject_id)->toBe($this->employee->id)
        ->and($activity->properties->get('relations'))->toBe(['employeeGroups' => ['old' => ['Денні'], 'new' => ['Нічні']]]);
});

it('logs sign-ins and failed sign-ins without the password', function () {
    Auth::logout();
    Activity::query()->delete();

    Auth::attempt(['email' => 'employee@test.local', 'password' => 'wrong-password']);
    $failed = lastActivity();
    Auth::attempt(['email' => 'employee@test.local', 'password' => 'secret-password']);

    expect($failed->event)->toBe('login_failed')
        ->and($failed->properties->get('email'))->toBe('employee@test.local')
        ->and(json_encode($failed->properties))->not->toContain('wrong-password')
        ->and(lastActivity()->event)->toBe('login')
        ->and(lastActivity()->causer_id)->toBe($this->employee->id);
});

it('queues the pruning at most once a day and deletes entries older than a year', function () {
    Queue::fake();
    Cache::forget('activity-log:pruning-dispatched');

    $this->employee->update(['position' => 'A']);
    $this->employee->update(['position' => 'B']);
    Queue::assertPushed(PruneActivityLog::class, 1);

    $old = lastActivity();
    $old->forceFill(['created_at' => now()->subDays(366)])->save();
    $recent = Activity::query()->whereKeyNot($old->id)->firstOrFail();

    (new PruneActivityLog)->handle();

    expect(Activity::find($old->id))->toBeNull()
        ->and(Activity::find($recent->id))->not->toBeNull();
});

it('shows the journal to administrators', function () {
    $this->employee->update(['position' => 'Черговий']);

    $this->get(ActivityLogResource::getUrl())->assertOk()->assertSee('Журнал дій');
});

it('hides the journal from managers', function () {
    $manager = User::create(['name' => 'Менеджер', 'email' => 'manager@test.local', 'password' => 'secret-password']);
    $manager->assignRole('Manager');
    // A fresh session for the other user (switching users within one session signs out).
    $this->flushSession();
    app('auth')->forgetGuards();

    $this->actingAs($manager)->get(ActivityLogResource::getUrl())->assertForbidden();
});

it('filters the journal by object for the history link and shows entry details', function () {
    $this->employee->update(['position' => 'Черговий']);
    $this->duty->update(['name' => 'Добове']);
    $userEntry = Activity::query()->where('subject_type', (new User)->getMorphClass())->sole();

    $this->get(ActivityLogResource::historyUrl($this->employee))->assertOk();

    Livewire::test(ListActivities::class, ['tableFilters' => ['subject' => ['type' => (new User)->getMorphClass(), 'id' => $this->employee->id]]])
        ->assertCanSeeTableRecords([$userEntry])
        ->assertCountTableRecords(1)
        ->mountTableAction('view', $userEntry)
        ->assertSee('Черговий');
});
